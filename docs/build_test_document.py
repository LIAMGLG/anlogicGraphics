def h(text): doc.add_heading(text, level=2)

def table(headers, rows, widths=None, blank=0):
    t = doc.add_table(rows=1, cols=len(headers))
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    if widths is None: widths = [17.6/len(headers)] * len(headers)
    for i,w in enumerate(widths): t.columns[i].width = Cm(w)
    def fill(row, vals, head=False):
        for i,txt in enumerate(vals):
            c = row.cells[i]
            c.width = Cm(widths[i])
            c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            c.text = str(txt)
            tcPr = c._tc.get_or_add_tcPr()
            borders = OxmlElement('w:tcBorders')
            for side in ['top','left','bottom','right']:
                b=OxmlElement('w:'+side); b.set(qn('w:val'),'single'); b.set(qn('w:sz'),'4'); b.set(qn('w:color'),'BAC2CA'); borders.append(b)
            tcPr.append(borders)
            if head:
                shade=OxmlElement('w:shd'); shade.set(qn('w:fill'),'E9EDF1'); tcPr.append(shade)
            for pp in c.paragraphs:
                pp.paragraph_format.space_after = Pt(3)
                pp.paragraph_format.space_before = Pt(3)
                pp.paragraph_format.line_spacing = 1.05
                for rr in pp.runs:
                    rr.font.size = Pt(9)
                    rr.bold = head
        pr=row._tr.get_or_add_trPr(); pr.append(OxmlElement('w:cantSplit'))
    fill(t.rows[0],headers,True)
    repeat=OxmlElement('w:tblHeader'); t.rows[0]._tr.get_or_add_trPr().append(repeat)
    for vals in rows: fill(t.add_row(),vals)
    for _ in range(blank): fill(t.add_row(),['']*len(headers))
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t

