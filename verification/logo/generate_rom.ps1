$ErrorActionPreference='Stop'
$root=[IO.Path]::GetFullPath((Join-Path $PSScriptRoot '../..'))
$source=Get-Content (Join-Path $root 'user_source/hdl_source/anlogic_logo_rom.v') -Raw -Encoding utf8
$pixels=New-Object 'int[]' 15360
foreach($entry in [regex]::Matches($source,"15'd(\d+):\s*O_pixel\s*=\s*25'h([0-9a-fA-F]+)")) {
    $address=[int]$entry.Groups[1].Value-160*32
    if($address -ge 0 -and $address -lt $pixels.Length) {
        $pixels[$address]=[Convert]::ToInt32($entry.Groups[2].Value,16)
    }
}
# Index zero is transparent; RGB distance assigns opaque antialias colours.
$palette=@(0xED1C24,0x1C2D4E,0xFFFFFF)
$indices=New-Object 'int[]' 15360
Add-Type -AssemblyName System.Drawing
$preview=New-Object Drawing.Bitmap 160,96
$counts=@(0,0,0,0)
for($i=0;$i -lt $pixels.Length;$i++) {
    if($pixels[$i] -band 0x1000000) {
        $bestDistance=[int]::MaxValue; $best=0
        for($p=0;$p -lt 3;$p++) {
            $distance=0
            foreach($shift in @(16,8,0)) {
                $difference=(($pixels[$i] -shr $shift)-band 255)-(($palette[$p] -shr $shift)-band 255)
                $distance+=$difference*$difference
            }
            if($distance -lt $bestDistance) {$bestDistance=$distance;$best=$p}
        }
        $indices[$i]=$best+1
        $rgb=$palette[$best]
        $preview.SetPixel($i%160,[int][Math]::Floor($i/160),[Drawing.Color]::FromArgb(255,($rgb -shr 16)-band 255,($rgb -shr 8)-band 255,$rgb-band 255))
    }
    $counts[$indices[$i]]++
}
$lines=New-Object 'Collections.Generic.List[string]'
$lines.Add('// Generated by verification/logo/generate_rom.ps1; source rows 32..127.')
$lines.Add('// Four 2-bit palette indices per word; 00 transparent, 01 red, 10 navy, 11 white.')
$lines.Add('module anlogic_logo_words(input wire I_clk,input wire [11:0] I_addr,output wire [99:0] O_pixels);')
$lines.Add('    reg [7:0] memory[0:3839];')
$lines.Add('    reg [7:0] indices;')
$lines.Add('    initial begin')
for($i=0;$i -lt 3840;$i++) {
    $word=($indices[$i*4]-shl 6)-bor ($indices[$i*4+1]-shl 4)-bor ($indices[$i*4+2]-shl 2)-bor $indices[$i*4+3]
    $lines.Add(('        memory[{0}]=8''h{1:X2};' -f $i,$word))
}
$lines.Add('    end')
$lines.Add('    function [24:0] decode;')
$lines.Add('        input [1:0] index;')
$lines.Add('        begin case(index)')
$lines.Add('            1: decode=25''h1ED1C24;')
$lines.Add('            2: decode=25''h11C2D4E;')
$lines.Add('            3: decode=25''h1FFFFFF;')
$lines.Add('            default: decode=25''h0000000;')
$lines.Add('        endcase end')
$lines.Add('    endfunction')
$lines.Add('    always @(posedge I_clk) indices<=memory[I_addr];')
$lines.Add('    assign O_pixels={decode(indices[7:6]),decode(indices[5:4]),decode(indices[3:2]),decode(indices[1:0])};')
$lines.Add('endmodule')
[IO.File]::WriteAllLines((Join-Path $root 'user_source/hdl_source/isp/anlogic_logo_words.v'),$lines,[Text.UTF8Encoding]::new($false))
$preview.Save((Join-Path $PSScriptRoot 'three_color.png'),[Drawing.Imaging.ImageFormat]::Png)
$preview.Dispose()
Write-Output ('PASS: generated 3840x8-bit ROM; index counts transparent/red/navy/white: '+($counts -join '/'))
